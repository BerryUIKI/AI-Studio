/**
 * Multi-Language Internationalization (i18n) Dictionary & Resolver
 * Supports 8 languages with "Follow System" and English default fallback.
 */

export type SupportedLanguage = 'en' | 'zh-CN' | 'ja' | 'ko' | 'fr' | 'de' | 'es' | 'ru';
export type LanguageSetting = 'system' | SupportedLanguage;

export interface LanguageOption {
  id: LanguageSetting;
  label: string;
  nativeLabel: string;
}

export const LANGUAGE_OPTIONS: LanguageOption[] = [
  { id: 'system', label: 'Follow System', nativeLabel: 'Auto (System)' },
  { id: 'en', label: 'English', nativeLabel: 'English (US)' },
  { id: 'zh-CN', label: 'Simplified Chinese', nativeLabel: '简体中文' },
  { id: 'ja', label: 'Japanese', nativeLabel: '日本語' },
  { id: 'ko', label: 'Korean', nativeLabel: '한국어' },
  { id: 'fr', label: 'French', nativeLabel: 'Français' },
  { id: 'de', label: 'German', nativeLabel: 'Deutsch' },
  { id: 'es', label: 'Spanish', nativeLabel: 'Español' },
  { id: 'ru', label: 'Russian', nativeLabel: 'Русский' },
];

export function resolveEffectiveLanguage(setting: LanguageSetting): SupportedLanguage {
  if (setting !== 'system') return setting;

  try {
    if (typeof navigator !== 'undefined' && navigator.language) {
      const navLang = navigator.language.toLowerCase();
      if (navLang.startsWith('zh')) return 'zh-CN';
      if (navLang.startsWith('ja')) return 'ja';
      if (navLang.startsWith('ko')) return 'ko';
      if (navLang.startsWith('fr')) return 'fr';
      if (navLang.startsWith('de')) return 'de';
      if (navLang.startsWith('es')) return 'es';
      if (navLang.startsWith('ru')) return 'ru';
      if (navLang.startsWith('en')) return 'en';
    }
  } catch {
    // ignore
  }

  // Strict fallback when undetectable or unknown
  return 'en';
}

